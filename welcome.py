def lang_of(text: str) -> str:
    if re.search(r"[\u0600-\u06FF]", text):
        return "ar"
    fr = {"le", "la", "les", "droit", "est", "que", "une", "des", "pour", "dans", "code", "article"}
    words = set(re.findall(r"[a-zàâäéèêëîïôöùûüç]+", text.lower()))
    return "fr" if words & fr else "en"

